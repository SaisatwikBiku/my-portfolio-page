/** Coastline rings as [lon, lat] pairs. Parsed on first use. */
export function coastRings() {
  if (!rings) {
    rings = ENCODED.split(';').map((r) =>
      r.split(' ').map((p) => {
        const [lon, lat] = p.split(',')
        return [+lon, +lat]
      }),
    )
  }
  return rings
}

